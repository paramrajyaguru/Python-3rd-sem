import math
num = float(input("Enter a number: "))
square = num ** 2
square_root = math.sqrt(num)  
cube = num ** 3
ceiling = math.ceil(num)

print("Square of the number:", square)
print("Square root of the number:", square_root)
print("Cube of the number:", cube)
print("Ceiling of the number:", ceiling)
print()
